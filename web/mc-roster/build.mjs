#!/usr/bin/env node
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../..");
const srcDir = path.join(__dirname, "src");
const assetsDir = path.join(__dirname, "assets");
const rustAssetsPath = path.join(repoRoot, "src/mission_control/assets.rs");

const BANNED_SINK_PATTERNS = [
  /\binnerHTML\b/,
  /\bouterHTML\b/,
  /\binsertAdjacentHTML\b/,
  /\bdocument\.write\b/,
  /\beval\s*\(/,
  /\bnew\s+Function\b/,
  /javascript:/i,
];

function checkBannedSinks() {
  for (const name of fs.readdirSync(srcDir)) {
    if (!name.endsWith(".ts")) continue;
    const full = path.join(srcDir, name);
    const content = fs.readFileSync(full, "utf8");
    for (const pat of BANNED_SINK_PATTERNS) {
      if (pat.test(content)) {
        throw new Error(`Banned DOM/script sink ${pat} found in ${full}`);
      }
    }
  }
}

function sha256Short(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex").slice(0, 12);
}

function buildArtifacts() {
  checkBannedSinks();
  const jsOut = execFileSync(
    "esbuild",
    [path.join(srcDir, "main.ts"), "--bundle", "--format=esm", "--target=es2022", "--minify"],
    { encoding: null },
  );
  const cssOut = execFileSync(
    "esbuild",
    [path.join(srcDir, "mc-roster.css"), "--minify"],
    { encoding: null },
  );
  const jsHash = sha256Short(jsOut);
  const cssHash = sha256Short(cssOut);
  const jsName = `mc-roster.${jsHash}.js`;
  const cssName = `mc-roster.${cssHash}.css`;
  const rustSrc = `// Generated by web/mc-roster/build.mjs. Do not edit by hand.

pub const JS_PATH: &str = "/assets/${jsName}";
pub const CSS_PATH: &str = "/assets/${cssName}";
pub const JS_BYTES: &[u8] = include_bytes!("../../web/mc-roster/assets/${jsName}");
pub const CSS_BYTES: &[u8] = include_bytes!("../../web/mc-roster/assets/${cssName}");
`;
  return { jsOut, cssOut, jsName, cssName, rustSrc };
}

const checkOnly = process.argv.includes("--check");
const { jsOut, cssOut, jsName, cssName, rustSrc } = buildArtifacts();

if (checkOnly) {
  const existingFiles = fs.existsSync(assetsDir) ? fs.readdirSync(assetsDir).sort() : [];
  const expectedFiles = [cssName, jsName].sort();
  if (JSON.stringify(existingFiles) !== JSON.stringify(expectedFiles)) {
    console.error(`Asset mismatch: expected ${expectedFiles.join(", ")}, got ${existingFiles.join(", ")}`);
    process.exit(1);
  }
  if (!fs.readFileSync(path.join(assetsDir, jsName)).equals(jsOut)) {
    console.error(`Stale JS asset: ${jsName}`);
    process.exit(1);
  }
  if (!fs.readFileSync(path.join(assetsDir, cssName)).equals(cssOut)) {
    console.error(`Stale CSS asset: ${cssName}`);
    process.exit(1);
  }
  if (fs.readFileSync(rustAssetsPath, "utf8") !== rustSrc) {
    console.error(`Stale ${rustAssetsPath}`);
    process.exit(1);
  }
  console.log(`mc-roster assets fresh: ${jsName}, ${cssName}`);
} else {
  fs.mkdirSync(assetsDir, { recursive: true });
  for (const old of fs.readdirSync(assetsDir)) {
    fs.unlinkSync(path.join(assetsDir, old));
  }
  fs.writeFileSync(path.join(assetsDir, jsName), jsOut);
  fs.writeFileSync(path.join(assetsDir, cssName), cssOut);
  fs.writeFileSync(rustAssetsPath, rustSrc);
  console.log(`Built ${jsName} (${jsOut.length} B), ${cssName} (${cssOut.length} B)`);
}
